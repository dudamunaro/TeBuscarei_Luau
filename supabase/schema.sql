CREATE TABLE IF NOT EXISTS public.inscritos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  idade integer NOT NULL CHECK (idade BETWEEN 11 AND 120),
  nome_responsavel text,
  telefone_responsavel text,
  telefone_participante text,
  ja_fez_retiro text,
  qual_retiro text,
  restricao_saude text,
  medicacao text,
  status_pagamento text NOT NULL DEFAULT 'pendente'
    CHECK (status_pagamento IN ('pendente', 'pago')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS inscritos_nome_idade_normalized_unique_idx
  ON public.inscritos (
    (lower(regexp_replace(btrim(nome), '[[:space:]]+', ' ', 'g'))),
    idade
  );

ALTER TABLE public.inscritos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.inscritos FROM anon, authenticated;
